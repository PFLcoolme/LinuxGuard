#!/bin/sh
# repairs/kernel_repair.sh - Kernel parameter repairs

LG_SYSCTL_CONF='/etc/sysctl.d/99-linuxguard.conf'

# Set a sysctl value immediately and persistently
_lg_sysctl_set() {
    _key=$1
    _value=$2

    if ! lg_command_exists sysctl; then
        printf 'sysctl not available / sysctl 不可用\n'
        return 1
    fi

    # Apply immediately
    if ! sysctl -w "${_key}=${_value}" >/dev/null 2>&1; then
        printf '  Failed to set %s=%s / 设置 %s=%s 失败\n' "$_key" "$_value" "$_key" "$_value"
        return 1
    fi

    # Persist
    if [ ! -f "$LG_SYSCTL_CONF" ]; then
        printf '# Generated by LinuxGuard\n' > "$LG_SYSCTL_CONF"
    fi

    if grep -qE "^[[:space:]]*${_key}[[:space:]]*=" "$LG_SYSCTL_CONF" 2>/dev/null; then
        sed "s|^[[:space:]]*${_key}[[:space:]]*=.*|${_key}=${_value}|" "$LG_SYSCTL_CONF" > "${LG_SYSCTL_CONF}.lgtmp" && mv "${LG_SYSCTL_CONF}.lgtmp" "$LG_SYSCTL_CONF"
    else
        printf '%s=%s\n' "$_key" "$_value" >> "$LG_SYSCTL_CONF"
    fi

    return 0
}

lg_repair_kernel_aslr() {
    printf '  Enabling kernel ASLR / 启用内核 ASLR\n'
    _lg_sysctl_set "kernel.randomize_va_space" "2"
}

lg_repair_kernel_kptr_restrict() {
    printf '  Enabling kernel.kptr_restrict / 启用 kernel.kptr_restrict\n'
    _lg_sysctl_set "kernel.kptr_restrict" "1"
}

lg_repair_kernel_modules_disabled() {
    printf '  Disabling new kernel module loading (one-way until reboot) / 禁用新内核模块加载（重启前单向）\n'
    _lg_sysctl_set "kernel.modules_disabled" "1"
}

lg_repair_kernel_ip_forward() {
    printf '  Disabling IPv4 forwarding / 禁用 IPv4 转发\n'
    _lg_sysctl_set "net.ipv4.ip_forward" "0"
}

lg_repair_kernel_rp_filter() {
    printf '  Enabling reverse path filtering / 启用反向路径过滤\n'
    _lg_sysctl_set "net.ipv4.conf.all.rp_filter" "1"
}
